"""SystemVerilog RTL style checker and fixer.

Exit codes: 0 clean (SHOULD findings allowed) · 1 a MUST violation · 2 I/O error
or missing required tool · 3 refused, the file does not parse · 4 internal bug,
svstyle broke its own invariant and wrote nothing.
"""

import argparse
import difflib
import json
import os
import re
import sys
from dataclasses import asdict
from pathlib import Path

from . import __version__, docgen, external
from .checks import PLACEHOLDER, ConfigError, apply_waivers, load_config, run_checks
from .fix import InvariantError, fix_text
from .parse import ParseError
from .rules import RULES_TOML, RulesError, by_category, load_rules, tool_index

# Generated artefacts, relative to the repo root. Regenerated by `rules --gen`
# and diffed by `rules --check`; never hand-edited.
REPO = Path(__file__).resolve().parents[2]
SKILL = REPO / "skill" / "systemverilog-rtl"
OUTPUTS = {
    REPO / "docs" / "style-guide.html": "html",
    SKILL / "references" / "rules.md": "compact",
    SKILL / "references" / "rules-rationale.md": "full",
}

# Cross-checked by --check once the Phase 2/3 artefacts exist.
CHECKS_PY = REPO / "src" / "svstyle" / "checks.py"
VERIBLE_LINT_CONFIG = REPO / "src" / "svstyle" / "data" / "rules.verible_lint"
SKILL_MD = SKILL / "SKILL.md"

RULE_ID_RE = re.compile(r"\b[A-Z]{3}-\d{3}\b")


def _render(kind: str, rules: list) -> str:
    if kind == "html":
        return docgen.render_html(rules)
    if kind == "compact":
        return docgen.render_markdown_compact(rules)
    return docgen.render_markdown_full(rules)


def _gen(rules: list) -> int:
    for path, kind in OUTPUTS.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(_render(kind, rules), encoding="utf-8")
        print(f"wrote {path.relative_to(REPO)}")
    return 0


def _check(rules: list) -> int:
    """The drift net: rules DB vs. implementation vs. configs vs. generated files."""
    problems: list[str] = []
    skipped: list[str] = []

    # 1. svstyle-owned rules must have an implementation in checks.py.
    own = tool_index(rules, "svstyle")
    if CHECKS_PY.exists():
        impl = CHECKS_PY.read_text(encoding="utf-8")
        for name, r in own.items():
            if f'rule="{name}"' not in impl and f"rule='{name}'" not in impl:
                problems.append(f"{r.id}: no implementation of rule={name!r} in checks.py")
    elif own:
        skipped.append(f"checks.py absent: {len(own)} svstyle rule(s) unverified (Phase 2)")

    # 2. Every verible-lint rule we cite must be enabled in the shipped config, and
    #    every rule the config enables must be claimed by a rule (both directions).
    cited = {n: r.id for n, r in tool_index(rules, "verible-lint").items()}
    if VERIBLE_LINT_CONFIG.exists():
        enabled = set()
        for line in VERIBLE_LINT_CONFIG.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith(("#", "-")):
                enabled.add(line.split("=", 1)[0].lstrip("+").strip())
        for name, rid in sorted(cited.items()):
            if name not in enabled:
                problems.append(f"{rid}: verible-lint rule {name!r} is not enabled in the config")
        for name in sorted(enabled - set(cited)):
            problems.append(f"config enables verible-lint rule {name!r} that no rule claims")
    elif cited:
        skipped.append(f"verible lint config absent: {len(cited)} mapping(s) unverified (Phase 2)")

    # 3. Every rule ID cited in SKILL.md must exist.
    ids = {r.id for r in rules}
    if SKILL_MD.exists():
        for rid in sorted(set(RULE_ID_RE.findall(SKILL_MD.read_text(encoding="utf-8")))):
            if rid not in ids:
                problems.append(f"SKILL.md cites {rid}, which is not in rules.toml")
    else:
        skipped.append("SKILL.md absent: citations unverified (Phase 3)")

    # 4. Generated files must be up to date.
    for path, kind in OUTPUTS.items():
        want = _render(kind, rules)
        if not path.exists():
            problems.append(f"{path.relative_to(REPO)} missing — run `svstyle rules --gen`")
        elif path.read_text(encoding="utf-8") != want:
            problems.append(f"{path.relative_to(REPO)} is stale — run `svstyle rules --gen`")

    for note in skipped:
        print(f"skip: {note}")
    for p in problems:
        print(f"drift: {p}", file=sys.stderr)
    print(f"{len(rules)} rules, {len(problems)} problem(s)")
    return 1 if problems else 0


def _unmapped(rules: list) -> int:
    """Rules no tool enforces — the human/skill-only surface."""
    for r in rules:
        if r.tool == "review":
            print(f"{r.id}  {r.severity:6s}  {r.statement}")
    return 0


def _show(rules: list, rid: str) -> int:
    for r in rules:
        if r.id == rid.upper():
            print(docgen.render_markdown_full([r]))
            return 0
    print(f"no such rule: {rid}", file=sys.stderr)
    return 2


def _list(rules: list) -> int:
    for cat, group in by_category(rules).items():
        print(f"\n{cat}")
        for r in group:
            fix = " [fix]" if r.autofix else ""
            print(f"  {r.id}  {r.severity:6s}  {r.statement}{fix}")
    return 0


EXIT_KIND = {0: "clean", 1: "violations", 2: "error", 3: "refused", 4: "bug"}


def _warn_verible_drift() -> None:
    try:
        found = external.verible_version()
    except external.ToolMissing:
        return
    if found != external.KNOWN_GOOD_VERIBLE_VERSION:
        print(
            f"warning: Verible {found}; svstyle is pinned to "
            f"{external.KNOWN_GOOD_VERIBLE_VERSION}, alignment may drift",
            file=sys.stderr,
        )


def _read(path: str, errors: list[str]) -> str | None:
    try:
        return Path(path).read_text(encoding="utf-8")
    except OSError as exc:
        errors.append(f"{path}: {exc.strerror}")
        return None
    except UnicodeDecodeError as exc:
        errors.append(f"{path}: not UTF-8 (byte {exc.start}); svstyle reads UTF-8 only")
        return None


def _keep(rule: str, select: str | None, ignore: str | None) -> bool:
    """ruff-style prefixes: `--select DOC,PRT-001 --ignore DOC-005`."""
    if select and not rule.startswith(tuple(select.split(","))):
        return False
    return not (ignore and rule.startswith(tuple(ignore.split(","))))


def _report(
    args, diags: list, errors: list[str], code: int, configs: dict, extra: dict | None = None
) -> int:
    cli = (getattr(args, "select", None), getattr(args, "ignore", None))

    def keep(d) -> bool:
        # A selection on the command line replaces the file's, as in ruff.
        if any(cli):
            return _keep(d.rule, *cli)
        cfg = configs.get(str(Path(d.path).resolve()), {})
        return _keep(d.rule, ",".join(cfg.get("select", [])), ",".join(cfg.get("ignore", [])))

    diags = sorted(filter(keep, diags), key=lambda d: (d.path, d.line, d.col, d.rule))
    summary = {s: sum(d.severity == s for d in diags) for s in ("MUST", "SHOULD", "MAY")}
    if summary["MUST"]:
        code = max(code, 1)
    if args.json:
        doc = {
            "ok": code == 0,
            "exit_code": code,
            "kind": EXIT_KIND[code],
            "diagnostics": [{k: v for k, v in asdict(d).items() if k != "fix"} for d in diags],
            "summary": summary,
            **(extra or {}),
        }
        if errors:
            doc["error"] = "\n".join(errors)
        print(json.dumps(doc, indent=2))
        return code
    for d in diags:
        fix = " [fix available]" if d.fixable else ""
        print(f"{d.path}:{d.line}:{d.col}: {d.rule} {d.message}{fix}")
    for e in errors:
        print(f"error: {e}", file=sys.stderr)
    counts = ", ".join(f"{k} {v}" for k, v in summary.items() if v)
    print(f"{len(diags)} findings" + (f" ({counts})" if counts else ""))
    return code


def _cmd_check(args, rules: list) -> int:
    diags, errors, code, texts, configs = [], [], 0, {}, {}
    includes = dict.fromkeys(args.include)
    for path in args.files:
        text = _read(path, errors)
        if text is None:
            code = max(code, 2)
            continue
        try:
            cfg = configs[str(Path(path).resolve())] = load_config(path)
            inc = [*args.include, *cfg.get("include", [])]
            includes.update(dict.fromkeys(inc))
            diags += run_checks(text, path, rules, inc, cfg.get("company", PLACEHOLDER))
            texts[path] = text
        except ConfigError as exc:
            errors.append(str(exc))
            code = max(code, 2)
        except ParseError as exc:
            errors.append(str(exc))
            code = max(code, 3)
    parsed = list(texts)
    if parsed and not args.no_external:
        _warn_verible_drift()
        tools = (
            lambda: external.verible_verify(parsed, rules),
            lambda: external.verible_lint(parsed, rules),
            lambda: external.verilator_lint(parsed, rules, list(includes)),
        )
        # `synth = "yosys"` in the project config makes Yosys part of every check.
        if args.synth or any(c.get("synth") == "yosys" for c in configs.values()):
            tools += (lambda: external.yosys_check(parsed, rules, list(includes)),)
        for tool in tools:
            try:
                resolved = {str(Path(p).resolve()): t for p, t in texts.items()}
                for path, found in _by_path(tool()).items():
                    text = resolved.get(str(Path(path).resolve()))
                    diags += found if text is None else apply_waivers(found, text)
            except external.ToolMissing as exc:
                print(f"warning: {exc}; its rules were not checked", file=sys.stderr)
            except external.ToolFailed as exc:
                errors.append(f"{exc}; its rules were not checked")
                code = max(code, 2)
    return _report(args, diags, errors, code, configs)


def _by_path(diags: list) -> dict[str, list]:
    out: dict[str, list] = {}
    for d in diags:
        out.setdefault(d.path, []).append(d)
    return out


def _cmd_fix(args, rules: list) -> int:
    diags, errors, code, changed, configs = [], [], 0, 0, {}
    _warn_verible_drift()
    for path in args.files:
        text = _read(path, errors)
        if text is None:
            code = max(code, 2)
            continue
        try:
            cfg = configs[str(Path(path).resolve())] = load_config(path)
            inc = [*args.include, *cfg.get("include", [])]
            company = cfg.get("company", PLACEHOLDER)
            out = fix_text(text, path, rules, inc, company)
        except ConfigError as exc:
            errors.append(str(exc))
            code = max(code, 2)
            continue
        except external.ToolMissing as exc:
            errors.append(f"{exc}; fix needs it to stay idempotent")
            code = max(code, 2)
            continue
        except external.ToolFailed as exc:
            errors.append(f"{path}: {exc}")
            code = max(code, 2)
            continue
        except ParseError as exc:
            errors.append(str(exc))
            code = max(code, 3)
            continue
        except InvariantError as exc:
            errors.append(f"{exc} (please report; the file was not written)")
            code = max(code, 4)
            continue
        if out != text:
            changed += 1
            if args.diff:
                sys.stdout.writelines(
                    difflib.unified_diff(
                        text.splitlines(True),
                        out.splitlines(True),
                        f"a/{path.lstrip('/')}",
                        f"b/{path.lstrip('/')}",
                    )
                )
            else:
                # Write beside it, then rename: a crash never leaves half a file.
                tmp = Path(f"{path}.svstyle-tmp")
                tmp.write_text(out, encoding="utf-8")
                tmp.replace(path)
        diags += run_checks(out, path, rules, inc, company)  # left for the author
    if args.diff and changed:
        code = max(code, 1)  # a pending change fails CI, like `ruff format --diff`
    if not args.json:
        print(f"{'would fix' if args.diff else 'fixed'} {changed} file(s)")
    return _report(args, diags, errors, code, configs, {"files_changed": changed})


def _add_inputs(p: argparse.ArgumentParser) -> None:
    p.add_argument("files", nargs="*", type=Path, help="files, or directories to search for *.sv")
    p.add_argument(
        "-f",
        dest="filelists",
        metavar="FILE",
        action="append",
        default=[],
        type=lambda f: (f, False),
        help="filelist; paths relative to the cwd",
    )
    p.add_argument(
        "-F",
        dest="filelists",
        metavar="FILE",
        action="append",
        type=lambda f: (f, True),
        help="filelist; paths relative to the list",
    )
    p.add_argument("-I", "--include", metavar="DIR", action="append", default=[],
                   help="search DIR for `include files (repeatable)")  # fmt: skip


def _expand_inputs(args) -> None:
    """Directories become their *.sv files; filelists add files and +incdir+ dirs."""
    files: list[str] = []
    for f in args.files:
        files += sorted(map(str, f.rglob("*.sv"))) if f.is_dir() else [str(f)]
    for f, local in args.filelists:
        _read_filelist(Path(f), local, files, args.include)
    args.files = list(dict.fromkeys(files))


def _read_filelist(path: Path, local: bool, files: list[str], includes: list[str]) -> None:
    """The subset of the Verilator/VCS filelist syntax that names sources and includes.

    `-f` paths are relative to the cwd, `-F` paths to the list; `$VAR` expands;
    `//` comments and other simulator options (`+define+`, `-timescale`) are skipped.
    """
    base = path.parent if local else Path()
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = os.path.expandvars(raw.split("//", 1)[0]).strip()
        if line.startswith("+incdir+"):
            includes += [str(base / d) for d in line[len("+incdir+") :].split("+") if d]
        elif line[:3] in ("-f ", "-F "):
            _read_filelist(base / line[3:].strip(), line[1] == "F", files, includes)
        elif line and not line.startswith(("-", "+")):
            files.append(str(base / line))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="svstyle", description=__doc__.splitlines()[0])
    parser.add_argument("--version", action="version", version=f"svstyle {__version__}")
    sub = parser.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("rules", help="inspect, generate from, and validate the rules database")
    p.add_argument("--gen", action="store_true", help="regenerate HTML page and skill refs")
    p.add_argument("--check", action="store_true", help="fail on drift between DB, code and docs")
    p.add_argument("--unmapped", action="store_true", help="list rules no tool can enforce")
    p.add_argument("--id", metavar="ID", help="print one rule in full")
    p.add_argument("--html", metavar="OUT", type=Path, help="write the HTML page to OUT")
    p.add_argument("--markdown", metavar="OUT", type=Path, help="write the compact rules to OUT")
    p.add_argument("--toml", metavar="PATH", type=Path, help="read rules from PATH")

    p = sub.add_parser("check", help="report style violations (svstyle, Verible, Verilator)")
    _add_inputs(p)
    p.add_argument("--json", action="store_true", help="machine-readable output")
    p.add_argument("--no-external", action="store_true", help="skip Verible and Verilator")
    p.add_argument("--synth", action="store_true", help="also run Yosys: loops, drivers")
    p.add_argument("--select", metavar="IDS", help="only these rule IDs/prefixes, comma-separated")
    p.add_argument("--ignore", metavar="IDS", help="drop these rule IDs/prefixes, comma-separated")

    p = sub.add_parser("fix", help="format with Verible and insert missing comments/header")
    _add_inputs(p)
    p.add_argument("--json", action="store_true", help="machine-readable output")
    p.add_argument("--diff", action="store_true", help="print the diff instead of writing")

    args = parser.parse_args(argv)
    if args.cmd in ("check", "fix"):
        try:
            _expand_inputs(args)
        except OSError as exc:
            parser.error(f"{exc.filename}: {exc.strerror}")
        if not args.files:
            parser.error("no input files: pass FILES, a directory, or -f/-F FILELIST")

    try:
        rules = load_rules(getattr(args, "toml", None) or RULES_TOML)
    except (RulesError, OSError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    if args.cmd == "check":
        return _cmd_check(args, rules)
    if args.cmd == "fix":
        return _cmd_fix(args, rules)
    if args.id:
        return _show(rules, args.id)
    if args.html:
        args.html.write_text(docgen.render_html(rules), encoding="utf-8")
        print(f"wrote {args.html}")
    if args.markdown:
        args.markdown.write_text(docgen.render_markdown_compact(rules), encoding="utf-8")
        print(f"wrote {args.markdown}")
    if args.gen:
        return _gen(rules)
    if args.check:
        return _check(rules)
    if args.unmapped:
        return _unmapped(rules)
    if not (args.html or args.markdown):
        return _list(rules)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
