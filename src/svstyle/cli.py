# Generated artefacts, relative to the repo root. Regenerated by `rules --gen`
# and diffed by `rules --check`; never hand-edited.
REPO = Path(__file__).resolve().parents[2]
SKILL = REPO / "skill" / "systemverilog-rtl"


def _outputs() -> dict[Path, str]:
    from . import docgen  # only `rules` needs it; imported late to keep startup short

    return {
        REPO / "docs" / "style-guide.html": "html",
        SKILL / "references" / "rules.md": "compact:core",
        **{SKILL / "references" / f: f"compact:{c}" for c, f in docgen.ON_DEMAND.items()},
        SKILL / "references" / "rules-rationale.md": "full",
    }


# Cross-checked by --check.
CHECKS_PY = REPO / "src" / "svstyle" / "checks.py"
VERIBLE_LINT_CONFIG = REPO / "src" / "svstyle" / "data" / "rules.verible_lint"
SKILL_MD = SKILL / "SKILL.md"

RULE_ID_RE = re.compile(r"\b[A-Z]{3}-\d{3}\b")


def _render(kind: str, rules: list) -> str:
    from . import docgen

    if kind == "html":
        return docgen.render_html(rules, example=(SKILL / "assets" / "skeleton.sv").read_text())
    if kind.startswith("compact"):
        return docgen.render_markdown_compact(rules, kind.partition(":")[2])
    return docgen.render_markdown_full(rules)


def _gen(rules: list) -> int:
    for path, kind in _outputs().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(_render(kind, rules), encoding="utf-8")
        print(f"wrote {path.relative_to(REPO)}")
    return 0


def _check(rules: list) -> int:
    """The drift net: rules DB vs. implementation vs. configs vs. generated files."""
    problems: list[str] = []

    # 1. svstyle-owned rules must have an implementation in checks.py.
    impl = CHECKS_PY.read_text(encoding="utf-8")
    for name, r in tool_index(rules, "svstyle").items():
        if f'rule="{name}"' not in impl and f"rule='{name}'" not in impl:
            problems.append(f"{r.id}: no implementation of rule={name!r} in checks.py")

    # 2. Every verible-lint rule we cite must be enabled in the shipped config, and
    #    every rule the config enables must be claimed by a rule (both directions).
    cited = {n: r.id for n, r in tool_index(rules, "verible-lint").items()}
    enabled = set()
    for line in VERIBLE_LINT_CONFIG.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith(("#", "-")):
            enabled.add(line.split("=", 1)[0].lstrip("+").strip())
    for name, rid in sorted(cited.items()):
        if name not in enabled:
            problems.append(f"{rid}: verible-lint rule {name!r} is not enabled in the config")
    for name in sorted(enabled - set(cited)):
        problems.append(f"config enables verible-lint rule {name!r} that no rule claims")

    # 3. Every rule ID cited in SKILL.md and the hand-written references must exist.
    ids = {r.id for r in rules}
    for doc in [SKILL_MD, *sorted((SKILL / "references").glob("*.md"))]:
        if doc in _outputs():
            continue
        for rid in sorted(set(RULE_ID_RE.findall(doc.read_text(encoding="utf-8")))):
            if rid not in ids:
                problems.append(f"{doc.name} cites {rid}, which is not in rules.toml")

    # 4. Generated files must be up to date.
    for path, kind in _outputs().items():
        want = _render(kind, rules)
        if not path.exists():
            problems.append(f"{path.relative_to(REPO)} missing — run `svstyle rules --gen`")
        elif path.read_text(encoding="utf-8") != want:
            problems.append(f"{path.relative_to(REPO)} is stale — run `svstyle rules --gen`")

    for p in problems:
        print(f"drift: {p}", file=sys.stderr)
    print(f"{len(rules)} rules, {len(problems)} problem(s)")
    return 1 if problems else 0


def _unmapped(rules: list) -> int:
    """Rules no tool enforces — the human/skill-only surface."""
    for r in rules:
        if r.tool == "review":
            print(f"{r.id}  {r.severity:6s}  {r.statement}")
    return 0


def _show(rules: list, rid: str) -> int:
    from . import docgen

    for r in rules:
        if r.id == rid.upper():
            print(docgen.render_markdown_full([r]))
            return 0
    print(f"no such rule: {rid}", file=sys.stderr)
    return 2


def _list(rules: list) -> int:
    for cat, group in by_category(rules).items():
        print(f"\n{cat}")
        for r in group:
            fix = " [fix]" if r.autofix else ""
            print(f"  {r.id}  {r.severity:6s}  {r.statement}{fix}")
    return 0


EXIT_KIND = {0: "clean", 1: "violations", 2: "error", 3: "refused", 4: "bug"}


def _warn_verible_drift() -> None:
    try:
        found = external.verible_version()
    except external.ToolMissing:
        return
    if found not in external.KNOWN_GOOD_VERIBLE_VERSIONS:
        print(
            f"warning: Verible {found}; svstyle is tested with "
            f"{', '.join(external.KNOWN_GOOD_VERIBLE_VERSIONS)}, alignment may drift",
            file=sys.stderr,
        )


def _read(path: str, errors: list[str]) -> str | None:
    try:
        return Path(path).read_text(encoding="utf-8")
    except OSError as exc:
        errors.append(f"{path}: {exc.strerror}")
        return None
    except UnicodeDecodeError as exc:
        errors.append(f"{path}: not UTF-8 (byte {exc.start}); svstyle reads UTF-8 only")
        return None


def _filters(cfg: dict) -> tuple[str, str]:
    """A config's `select` / `ignore` lists as the comma-separated prefixes keep_rule takes."""
    return ",".join(cfg.get("select", [])), ",".join(cfg.get("ignore", []))


def _report(
    args, diags: list, errors: list[str], code: int, configs: dict, extra: dict | None = None
) -> int:
    cli = (getattr(args, "select", None), getattr(args, "ignore", None))

    def keep(d) -> bool:
        # A selection on the command line replaces the file's, as in ruff.
        if any(cli):
            return keep_rule(d.rule, *cli)
        cfg = configs.get(str(Path(d.path).resolve()), {})
        return keep_rule(d.rule, *_filters(cfg))

    diags = sorted(filter(keep, diags), key=lambda d: (d.path, d.line, d.col, d.rule))
    summary = {s: sum(d.severity == s for d in diags) for s in ("MUST", "SHOULD", "MAY")}
    if summary["MUST"]:
        code = max(code, 1)
    if args.json:
        doc = {
            "ok": code == 0,
            "exit_code": code,
            "kind": EXIT_KIND[code],
            "diagnostics": [{k: v for k, v in asdict(d).items() if k != "fix"} for d in diags],
            "summary": summary,
            **(extra or {}),
        }
        if errors:
            doc["error"] = "\n".join(errors)
        print(json.dumps(doc, indent=2))
        return code
    for d in diags:
        fix = " [fix available]" if d.fixable else ""
        if getattr(args, "github", False):
            print(_annotation(d, fix))
        else:
            print(f"{d.path}:{d.line}:{d.col}: {d.rule} {d.message}{fix}")
    for e in errors:
        print(f"error: {e}", file=sys.stderr)
    counts = ", ".join(f"{k} {v}" for k, v in summary.items() if v)
    unchecked = f"; {len(errors)} error(s), see above" if errors else ""
    print(f"{len(diags)} findings" + (f" ({counts})" if counts else "") + unchecked)
    return code


GITHUB_LEVEL = {"MUST": "error", "SHOULD": "warning", "MAY": "notice"}


def _annotation(d, fix: str) -> str:
    """A GitHub Actions workflow command, shown on the PR diff at the line."""

    def esc(s: str, prop: bool = False) -> str:
        s = s.replace("%", "%25").replace("\r", "%0D").replace("\n", "%0A")
        return s.replace(":", "%3A").replace(",", "%2C") if prop else s

    where = f"file={esc(d.path, True)},line={d.line},col={d.col},title={d.rule}"
    return f"::{GITHUB_LEVEL[d.severity]} {where}::{esc(d.message + fix)}"


def _cmd_check(args, rules: list) -> int:
    diags, errors, code, texts, configs = [], [], 0, {}, {}
    includes = dict.fromkeys(args.include)
    defined: set[str] = set()  # modules and interfaces the files define
    used: set[str] = set()  # and the ones they instantiate
    jobs = []
    for path in args.files:
        text = _read(path, errors)
        if text is None:
            code = max(code, 2)
            continue
        try:
            cfg = configs[str(Path(path).resolve())] = load_config(path)
        except ConfigError as exc:
            errors.append(str(exc))
            code = max(code, 2)
            continue
        inc = [*args.include, *cfg.get("include", [])]
        includes.update(dict.fromkeys(inc))
        jobs.append((text, path, rules, inc, cfg.get("company", PLACEHOLDER)))
    for (text, path, *_), res in zip(jobs, _pmap(_check_job, jobs), strict=True):
        if isinstance(res, ParseError):
            errors.append(str(res))
            code = max(code, 3)
            continue
        if isinstance(res, Exception):
            errors.append(_internal(res, path))
            code = max(code, 4)
            continue
        found, ports, instantiated = res
        diags += found
        defined.update(ports)
        used.update(instantiated)
        texts[path] = text
    parsed = list(texts)
    if parsed and not args.no_external:
        _warn_verible_drift()
        tools = (
            lambda: external.verible_verify(parsed, rules),
            lambda: external.verible_lint(parsed, rules),
            lambda: external.verilator_lint(parsed, rules, list(includes)),
        )
        # `synth = "yosys"` (or "yosys-slang") in the project config makes Yosys
        # part of every check; "yosys-slang" also reads with the slang plugin.
        synths = {c.get("synth") for c in configs.values()}
        if args.synth or synths & {"yosys", "yosys-slang"}:
            # A module nobody passed is a black box to Yosys: its outputs look undriven.
            partial = bool(used - defined)
            slang = "yosys-slang" in synths
            tools += (lambda: external.yosys_check(parsed, rules, list(includes), partial, slang),)
        # The tools are separate processes: run them at once, report in order.
        from concurrent.futures import ThreadPoolExecutor

        with ThreadPoolExecutor(len(tools)) as pool:
            runs = [pool.submit(tool) for tool in tools]
        resolved = {str(Path(p).resolve()): t for p, t in texts.items()}
        for run in runs:
            try:
                for path, found in _by_path(run.result()).items():
                    text = resolved.get(str(Path(path).resolve()))
                    diags += found if text is None else apply_waivers(found, text)
            except external.ToolMissing as exc:
                print(f"warning: {exc}; its rules were not checked", file=sys.stderr)
            except external.ToolFailed as exc:
                errors.append(f"{exc}; its rules were not checked")
                code = max(code, 2)
    if not args.baseline:
        return _report(args, diags, errors, code, configs)
    try:
        new = _baseline(Path(args.baseline), diags, texts, args.write_baseline)
    except (OSError, ValueError, KeyError) as exc:
        print(f"error: baseline {args.baseline}: {exc}", file=sys.stderr)
        return 2
    if hidden := len(diags) - len(new):
        print(f"{hidden} finding(s) hidden by the baseline", file=sys.stderr)
    return _report(args, new, errors, code, configs, {"baselined": hidden})


def _baseline(path: Path, diags: list, texts: dict, write: bool) -> list:
    """Drop findings already in the baseline; with `write`, record them all first.

    A finding is keyed by file (relative to the baseline), rule and the text of
    its line, not the line number, so code moving around does not resurface it.
    Counted: a second identical finding on a new line is new.
    """
    root = path.resolve().parent
    lines = {str(Path(p).resolve()): t.splitlines() for p, t in texts.items()}

    def key(d) -> str:
        src = lines.get(str(Path(d.path).resolve()), [])
        text = src[d.line - 1].strip() if 0 < d.line <= len(src) else ""
        return f"{Path(os.path.relpath(Path(d.path).resolve(), root)).as_posix()}\t{d.rule}\t{text}"

    keys = [key(d) for d in diags]
    if write:
        doc = {"version": 1, "findings": sorted(keys)}
        path.write_text(json.dumps(doc, indent=1) + "\n", encoding="utf-8")
    known = Counter(json.loads(path.read_text(encoding="utf-8"))["findings"])
    out = []
    for d, k in zip(diags, keys, strict=True):
        if known[k]:
            known[k] -= 1
        else:
            out.append(d)
    return out


def _by_path(diags: list) -> dict[str, list]:
    out: dict[str, list] = {}
    for d in diags:
        out.setdefault(d.path, []).append(d)
    return out


def _design_ports(paths: list[str], include: list[str]) -> dict:
    """Every module's ports across the files given, so fix sees inouts in other files."""
    ports: dict = {}
    for found in _pmap(_ports_job, [(p, include) for p in paths]):
        if not isinstance(found, Exception):  # an unreadable file is reported later
            ports.update(found)
    return ports


# --- per-file work, spread over the cores --------------------------------------


def _pmap(fn, jobs: list[tuple]) -> list:
    """`fn(*job)` for each job, in order, on every core when there are several.

    An exception comes back as that job's result, so each file is reported on
    its own. Files are independent; only the slow part (pyslang, Verible) runs here.
    """
    if len(jobs) < 2:
        return [_call(fn, job) for job in jobs]
    from concurrent.futures import ProcessPoolExecutor  # a single file never needs it

    with ProcessPoolExecutor() as pool:
        return list(pool.map(_call, [fn] * len(jobs), jobs))


def _call(fn, job: tuple):
    try:
        return fn(*job)
    except Exception as exc:  # noqa: BLE001 - handed back to the parent to report
        return exc


def _ports_job(path: str, include: list[str]) -> dict:
    return parse(Path(path).read_text(encoding="utf-8"), path, include).ports


def _check_job(text: str, path: str, rules: list, inc: list[str], company: str):
    src = parse(text, path, inc)
    return run_checks(text, path, rules, inc, company, src), set(src.ports), src.instantiated


def _fix_job(
    text: str, path: str, rules: list, inc: list[str], company: str, ports: dict, filters: tuple
):
    out, src = fix_and_parse(text, path, rules, inc, company, ports, filters)
    return out, run_checks(out, path, rules, inc, company, src)


def _fix_failure(exc: Exception, path: str) -> tuple[str, int]:
    """What to tell the user when fixing `path` raised `exc`, and the exit code."""
    if isinstance(exc, external.ToolMissing):
        return f"{exc}; fix needs it to stay idempotent", 2
    if isinstance(exc, external.ToolFailed):
        return f"{path}: {exc}", 2
    if isinstance(exc, ParseError):
        return str(exc), 3
    if isinstance(exc, InvariantError):
        return f"{exc} (please report; the file was not written)", 4
    return _internal(exc, path) + "; the file was not written", 4


def _internal(exc: Exception, path: str) -> str:
    return f"{path}: internal error, please report: {type(exc).__name__}: {exc}"


def _cmd_fix(args, rules: list) -> int:
    diags, errors, code, changed, configs = [], [], 0, 0, {}
    _warn_verible_drift()
    ports = _design_ports(args.files, args.include) if len(args.files) > 1 else {}
    jobs = []
    for path in args.files:
        text = _read(path, errors)
        if text is None:
            code = max(code, 2)
            continue
        try:
            cfg = configs[str(Path(path).resolve())] = load_config(path)
        except ConfigError as exc:
            errors.append(str(exc))
            code = max(code, 2)
            continue
        inc = [*args.include, *cfg.get("include", [])]
        company = cfg.get("company", PLACEHOLDER)
        jobs.append((text, path, rules, inc, company, ports, _filters(cfg)))
    for (text, path, *_), res in zip(jobs, _pmap(_fix_job, jobs), strict=True):
        if isinstance(res, Exception):
            why, exit_code = _fix_failure(res, path)
            errors.append(why)
            code = max(code, exit_code)
            continue
        out, left = res
        if out != text:
            changed += 1
            if args.diff:
                sys.stdout.writelines(
                    difflib.unified_diff(
                        text.splitlines(True),
                        out.splitlines(True),
                        f"a/{path.lstrip('/')}",
                        f"b/{path.lstrip('/')}",
                    )
                )
            else:
                # Write beside it, then rename: a crash never leaves half a file.
                tmp = Path(f"{path}.svstyle-tmp")
                tmp.write_text(out, encoding="utf-8")
                tmp.replace(path)
        diags += left  # what the author still has to do
    if args.diff and changed:
        code = max(code, 1)  # a pending change fails CI, like `ruff format --diff`
    if not args.json:
        print(f"{'would fix' if args.diff else 'fixed'} {changed} file(s)")
    return _report(args, diags, errors, code, configs, {"files_changed": changed})


def _add_inputs(p: argparse.ArgumentParser) -> None:
    p.add_argument("files", nargs="*", type=Path, help="files, or directories to search for *.sv")
    p.add_argument(
        "-f",
        dest="filelists",
        metavar="FILE",
        action="append",
        default=[],
        type=lambda f: (f, False),
        help="filelist; paths relative to the cwd",
    )
    p.add_argument(
        "-F",
        dest="filelists",
        metavar="FILE",
        action="append",
        type=lambda f: (f, True),
        help="filelist; paths relative to the list",
    )
    p.add_argument("-I", "--include", metavar="DIR", action="append", default=[],
                   help="search DIR for `include files (repeatable)")  # fmt: skip


def _expand_inputs(args) -> None:
    """Directories become their *.sv files; filelists add files and +incdir+ dirs."""
    files: list[str] = []
    found: list[str] = []  # discovered, not named: `exclude` applies to these
    for f in args.files:
        if f.is_dir():
            found += sorted(map(str, f.rglob("*.sv")))
        else:
            files.append(str(f))
    for f, local in args.filelists:
        _read_filelist(Path(f), local, found, args.include)
    files += [f for f in found if not _excluded(f)]
    args.files = list(dict.fromkeys(files))


def _excluded(path: str) -> bool:
    """`exclude` globs from the nearest `.svstyle.toml`, against the path relative to it.

    fnmatch-style, so `*` also crosses directories: `vendor/*` is the whole tree.
    """
    cfg = load_config(path)
    root = cfg.get("root")
    if not cfg.get("exclude") or root is None:
        return False
    rel = Path(os.path.relpath(Path(path).resolve(), root)).as_posix()
    return any(fnmatch.fnmatchcase(rel, pat) for pat in cfg["exclude"])


def _read_filelist(
    path: Path, local: bool, files: list[str], includes: list[str], stack: tuple = ()
) -> None:
    """The subset of the Verilator/VCS filelist syntax that names sources and includes.

    `-f` paths are relative to the cwd, `-F` paths to the list; `$VAR` expands;
    `//` comments and other simulator options (`+define+`, `-timescale`) are skipped.
    """
    if (here := path.resolve()) in stack:
        raise OSError(errno.ELOOP, "filelist includes itself", str(path))
    base = path.parent if local else Path()
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = os.path.expandvars(raw.split("//", 1)[0]).strip()
        if line.startswith("+incdir+"):
            includes += [str(base / d) for d in line[len("+incdir+") :].split("+") if d]
        elif line[:3] in ("-f ", "-F "):
            nested = base / line[3:].strip()
            _read_filelist(nested, line[1] == "F", files, includes, (*stack, here))
        elif line and not line.startswith(("-", "+")):
            files.append(str(base / line))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="svstyle", description=__doc__.splitlines()[0])
    parser.add_argument("--version", action="version", version=f"svstyle {__version__}")
    sub = parser.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("rules", help="inspect, generate from, and validate the rules database")
    p.add_argument("--gen", action="store_true", help="regenerate HTML page and skill refs")
    p.add_argument("--check", action="store_true", help="fail on drift between DB, code and docs")
    p.add_argument("--unmapped", action="store_true", help="list rules no tool can enforce")
    p.add_argument("--id", metavar="ID", help="print one rule in full")
    p.add_argument("--html", metavar="OUT", type=Path, help="write the HTML page to OUT")
    p.add_argument("--markdown", metavar="OUT", type=Path, help="write the compact rules to OUT")
    p.add_argument("--toml", metavar="PATH", type=Path, help="read rules from PATH")

    p = sub.add_parser("check", help="report style violations (svstyle, Verible, Verilator)")
    _add_inputs(p)
    out = p.add_mutually_exclusive_group()
    out.add_argument("--json", action="store_true", help="machine-readable output")
    out.add_argument("--github", action="store_true", help="GitHub Actions annotations")
    p.add_argument("--no-external", action="store_true", help="skip Verible and Verilator")
    p.add_argument("--synth", action="store_true", help="also run Yosys: loops, drivers")
    p.add_argument("--select", metavar="IDS", help="only these rule IDs/prefixes, comma-separated")
    p.add_argument("--ignore", metavar="IDS", help="drop these rule IDs/prefixes, comma-separated")
    p.add_argument("--baseline", metavar="FILE", help="report only findings not in FILE")
    p.add_argument(
        "--write-baseline", action="store_true", help="record every finding in --baseline FILE"
    )

    p = sub.add_parser("fix", help="format with Verible and insert missing comments/header")
    _add_inputs(p)
    p.add_argument("--json", action="store_true", help="machine-readable output")
    p.add_argument("--diff", action="store_true", help="print the diff instead of writing")

    args = parser.parse_args(argv)
    _config_from.cache_clear()  # a config may have changed since the last call
    if getattr(args, "write_baseline", False) and not args.baseline:
        parser.error("--write-baseline needs --baseline FILE")
    if args.cmd in ("check", "fix"):
        try:
            _expand_inputs(args)
        except OSError as exc:
            parser.error(f"{exc.filename}: {exc.strerror}")
        except ConfigError as exc:
            parser.error(str(exc))
        if missing := [d for d in args.include if not Path(d).is_dir()]:
            parser.error(f"-I {missing[0]}: no such directory")
        if not args.files:
            parser.error(
                "no input files: pass FILES, a directory (its *.sv; name .v files), "
                "or -f/-F FILELIST"
            )

    try:
        rules = load_rules(getattr(args, "toml", None) or RULES_TOML)
    except (RulesError, OSError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    if args.cmd == "check":
        return _cmd_check(args, rules)
    if args.cmd == "fix":
        return _cmd_fix(args, rules)
    if args.id:
        return _show(rules, args.id)
    from . import docgen

    if args.html:
        args.html.write_text(docgen.render_html(rules), encoding="utf-8")
        print(f"wrote {args.html}")
    if args.markdown:
        args.markdown.write_text(docgen.render_markdown_compact(rules), encoding="utf-8")
        print(f"wrote {args.markdown}")
    if (args.gen or args.check) and not SKILL_MD.exists():
        # Installed from a wheel, REPO is site-packages: nothing to generate or diff.
        print("error: rules --gen/--check work only in a checkout of the svstyle repo",
              file=sys.stderr)  # fmt: skip
        return 2
    if args.gen:
        return _gen(rules)
    if args.check:
        return _check(rules)
    if args.unmapped:
        return _unmapped(rules)
    if not (args.html or args.markdown):
        return _list(rules)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
